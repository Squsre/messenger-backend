"""Uploaded photos and files.

The binary is stored by :mod:`app.services.storage`, never in the database. A
row records the safe display metadata plus three relationships:

* the **conversation** the upload belongs to (authorization boundary),
* the **uploader** (only they may attach it to their own message), and
* optionally the **message** it is attached to.

``message_id`` is unique, so one message has at most one attachment. The public
id and the storage key are both random server-generated values; a user-supplied
filename is only a display label and never influences the path on disk.

``status`` is currently always ``ready`` because validation happens
synchronously. It is persisted (and constrained) so a later asynchronous
pipeline (thumbnails, malware scan) can introduce ``pending``/``failed`` without
a schema rewrite.
"""

from __future__ import annotations

from datetime import datetime
from typing import TYPE_CHECKING, Optional

from sqlalchemy import (
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    UniqueConstraint,
    func,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

if TYPE_CHECKING:  # pragma: no cover - typing only
    from app.db.models.conversation import Conversation
    from app.db.models.message import Message
    from app.db.models.user import User


class Media(Base):
    """A stored photo/file attached to (or waiting for) one message."""

    __tablename__ = "media"
    __table_args__ = (
        CheckConstraint("size_bytes > 0", name="size_positive"),
        CheckConstraint(
            "(width IS NULL AND height IS NULL) OR "
            "(width IS NOT NULL AND height IS NOT NULL AND width > 0 AND height > 0)",
            name="dimensions_valid",
        ),
        CheckConstraint(
            "status IN ('pending', 'ready', 'failed')",
            name="status_allowed",
        ),
        UniqueConstraint("public_id", name="uq_media_public_id"),
        UniqueConstraint("storage_key", name="uq_media_storage_key"),
        # One attachment per message; also the guarantee behind the attach API.
        UniqueConstraint("message_id", name="uq_media_message_id"),
        Index("ix_media_conversation_id_created_at", "conversation_id", "created_at"),
    )

    id: Mapped[int] = mapped_column(primary_key=True, autoincrement=True)
    #: Unguessable API identifier; the internal id is never exposed.
    public_id: Mapped[str] = mapped_column(String(32), nullable=False)
    #: Opaque storage key generated by the server (never a user filename).
    storage_key: Mapped[str] = mapped_column(String(128), nullable=False)
    original_filename: Mapped[str] = mapped_column(String(255), nullable=False)
    content_type: Mapped[str] = mapped_column(String(100), nullable=False)
    size_bytes: Mapped[int] = mapped_column(Integer, nullable=False)
    width: Mapped[int | None] = mapped_column(Integer, nullable=True)
    height: Mapped[int | None] = mapped_column(Integer, nullable=True)
    status: Mapped[str] = mapped_column(
        String(20), nullable=False, default="ready", server_default="ready"
    )

    conversation_id: Mapped[int] = mapped_column(
        ForeignKey("conversations.id", ondelete="CASCADE"),
        nullable=False,
    )
    uploader_id: Mapped[int] = mapped_column(
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    message_id: Mapped[int | None] = mapped_column(
        ForeignKey("messages.id", ondelete="SET NULL"),
        nullable=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )

    conversation: Mapped["Conversation"] = relationship("Conversation")
    uploader: Mapped["User"] = relationship("User")
    message: Mapped[Optional["Message"]] = relationship("Message")

    def __repr__(self) -> str:  # pragma: no cover - debugging helper
        return (
            f"<Media id={self.id!r} public_id={self.public_id!r} "
            f"conversation={self.conversation_id!r} message={self.message_id!r}>"
        )
