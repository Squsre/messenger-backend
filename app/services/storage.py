"""Pluggable media storage.

The HTTP layer only knows the small :class:`StorageService` interface below.
The local-disk implementation is used in development and tests; a future MinIO
or S3 backend can implement the same methods (``save``/``read``/``delete``)
without touching the endpoints or the database schema.

Storage keys are generated by the server (random 128-bit hex + a safe
extension), never derived from a user's filename. This is the primary defence
against path traversal: even a hostile name can only become a display label.
The local backend additionally validates the key and confines every path to its
configured root.
"""

from __future__ import annotations

import os
import re
import secrets
from pathlib import Path
from typing import Protocol

from app.core.config import Settings


class StorageError(Exception):
    """Base class for storage failures (never exposed verbatim to clients)."""


class StorageObjectNotFound(StorageError):
    """The database row exists but the stored object is missing."""


class StorageService(Protocol):
    """Minimal backend interface used by the media endpoints."""

    def save(self, key: str, data: bytes) -> None:
        """Persist ``data`` under the server-generated ``key``."""

    def read(self, key: str) -> bytes:
        """Return the stored bytes, or raise :class:`StorageObjectNotFound`."""

    def delete(self, key: str) -> bool:
        """Remove the object; return whether it existed."""

    def exists(self, key: str) -> bool:
        """Whether the object exists in this backend."""


#: ``<32 hex>.<1-5 lowercase alphanumerics>``. The extension comes from the
#: detected content type, never from the uploaded filename.
_STORAGE_KEY_RE = re.compile(r"^[0-9a-f]{32}\.[a-z0-9]{1,5}$")


def new_storage_key(extension: str) -> str:
    """Create an unguessable key with a server-chosen extension."""
    suffix = extension.lower().lstrip(".")
    if not re.fullmatch(r"[a-z0-9]{1,5}", suffix):
        raise ValueError("invalid media extension")
    return f"{secrets.token_hex(16)}.{suffix}"


class LocalStorage:
    """Store objects as files under ``root``, sharded by key prefix.

    Files are written to a temporary name in the destination directory and
    atomically renamed, so a crash cannot leave a half-written object at the
    final key. The root directory is created lazily on the first save.
    """

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).expanduser().resolve()

    def _path(self, key: str) -> Path:
        if not _STORAGE_KEY_RE.fullmatch(key):
            # A corrupt database value must not become a path.
            raise StorageError("invalid storage key")
        path = (self.root / key[:2] / key[2:4] / key).resolve()
        if not path.is_relative_to(self.root):
            raise StorageError("invalid storage key")
        return path

    def save(self, key: str, data: bytes) -> None:
        path = self._path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = path.with_name(f"{path.name}.tmp-{secrets.token_hex(8)}")
            try:
                with temporary.open("xb") as handle:
                    handle.write(data)
                    handle.flush()
                    os.fsync(handle.fileno())
                os.replace(temporary, path)
            finally:
                temporary.unlink(missing_ok=True)
            if os.name == "posix":  # pragma: no cover - Windows dev/test host
                os.chmod(path, 0o600)
        except OSError as exc:
            raise StorageError("could not store the file") from exc

    def read(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return path.read_bytes()
        except FileNotFoundError as exc:
            raise StorageObjectNotFound("stored file is missing") from exc
        except OSError as exc:
            raise StorageError("could not read the file") from exc

    def delete(self, key: str) -> bool:
        path = self._path(key)
        try:
            path.unlink()
        except FileNotFoundError:
            return False
        except OSError as exc:
            raise StorageError("could not delete the file") from exc
        return True

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()


def build_storage(settings: Settings) -> StorageService:
    """Build the configured backend.

    Only ``local`` exists in this phase; the factory is the single place a
    future ``s3``/``minio`` branch has to be added.
    """
    if settings.media_storage_backend == "local":
        return LocalStorage(settings.media_storage_path)
    # Settings validates the allowed set, so this is defensive only.
    raise ValueError(f"unsupported media storage backend: {settings.media_storage_backend}")
