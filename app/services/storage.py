"""Pluggable media storage.

The HTTP layer only knows the small :class:`StorageService` interface below.
Two implementations are provided:

* :class:`LocalStorage` — development and test fallback, writing atomically to a
  confined directory.
* :class:`MinioStorage` — durable, private S3-compatible object storage used by
  the Compose stack.

Storage keys are generated by the server (random 128-bit hex + a safe
extension), never derived from a user's filename. This is the primary defence
against path traversal: even a hostile name can only become a display label.
MinIO object names additionally receive an optional application/environment
prefix, which lets tests and multiple deployments share a bucket without seeing
each other's objects.
"""

from __future__ import annotations

import io
import os
import re
import secrets
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Iterable, Protocol

import urllib3
from minio import Minio
from minio.error import MinioException, S3Error

from app.core.config import Settings


class StorageError(Exception):
    """Base class for storage failures (never exposed verbatim to clients)."""


class StorageObjectNotFound(StorageError):
    """The database row exists but the stored object is missing."""


class StorageUnsupported(StorageError):
    """The configured backend cannot provide the requested operation."""


@dataclass(frozen=True)
class StoredObject:
    """Result of a successful write."""

    backend: str
    etag: str | None = None


@dataclass(frozen=True)
class StorageObjectInfo:
    """Metadata needed by the orphan sweeper (never exposed by the API)."""

    key: str
    size_bytes: int
    last_modified: datetime
    etag: str | None = None


class StorageService(Protocol):
    """Minimal backend interface used by the media endpoints."""

    backend_name: str

    def save(
        self,
        key: str,
        data: bytes,
        *,
        content_type: str | None = None,
    ) -> StoredObject:
        """Persist ``data`` under the server-generated ``key``."""

    def read(self, key: str) -> bytes:
        """Return the stored bytes, or raise :class:`StorageObjectNotFound`."""

    def delete(self, key: str) -> bool:
        """Remove the object; return whether it existed."""

    def exists(self, key: str) -> bool:
        """Whether the object exists in this backend."""

    def presigned_url(self, key: str, *, expires_seconds: int) -> str:
        """Return a short-lived URL, or raise :class:`StorageUnsupported`."""

    def iter_objects(self, prefix: str = "") -> Iterable[StorageObjectInfo]:
        """Yield stored objects (used by the orphan sweeper)."""

    def health(self) -> bool:
        """Whether the backend is reachable and ready for operations."""

    def close(self) -> None:
        """Release backend resources. Must be safe to call more than once."""


#: ``<32 hex>.<1-5 lowercase alphanumerics>``. The extension comes from the
#: detected content type, never from the uploaded filename.
_STORAGE_KEY_RE = re.compile(r"^[0-9a-f]{32}\.[a-z0-9]{1,5}$")


def new_storage_key(extension: str) -> str:
    """Create an unguessable key with a server-chosen extension."""
    suffix = extension.lower().lstrip(".")
    if not re.fullmatch(r"[a-z0-9]{1,5}", suffix):
        raise ValueError("invalid media extension")
    return f"{secrets.token_hex(16)}.{suffix}"


def _validate_key(key: str) -> str:
    if not _STORAGE_KEY_RE.fullmatch(key):
        # A corrupt database value must not become a path or object name.
        raise StorageError("invalid storage key")
    return key


class LocalStorage:
    """Store objects as files under ``root``, sharded by key prefix.

    Files are written to a temporary name in the destination directory and
    atomically renamed, so a crash cannot leave a half-written object at the
    final key. The root directory is created lazily on the first save.
    """

    backend_name = "local"

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).expanduser().resolve()

    def _path(self, key: str) -> Path:
        _validate_key(key)
        path = (self.root / key[:2] / key[2:4] / key).resolve()
        if not path.is_relative_to(self.root):
            raise StorageError("invalid storage key")
        return path

    def save(
        self,
        key: str,
        data: bytes,
        *,
        content_type: str | None = None,
    ) -> StoredObject:
        path = self._path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            temporary = path.with_name(f"{path.name}.tmp-{secrets.token_hex(8)}")
            try:
                with temporary.open("xb") as handle:
                    handle.write(data)
                    handle.flush()
                    os.fsync(handle.fileno())
                os.replace(temporary, path)
            finally:
                temporary.unlink(missing_ok=True)
            if os.name == "posix":  # pragma: no cover - Windows dev/test host
                os.chmod(path, 0o600)
        except OSError as exc:
            raise StorageError("could not store the file") from exc
        return StoredObject(backend=self.backend_name)

    def read(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return path.read_bytes()
        except FileNotFoundError as exc:
            raise StorageObjectNotFound("stored file is missing") from exc
        except OSError as exc:
            raise StorageError("could not read the file") from exc

    def delete(self, key: str) -> bool:
        path = self._path(key)
        try:
            path.unlink()
        except FileNotFoundError:
            return False
        except OSError as exc:
            raise StorageError("could not delete the file") from exc
        return True

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()

    def presigned_url(self, key: str, *, expires_seconds: int) -> str:
        raise StorageUnsupported("local storage does not provide direct URLs")

    def iter_objects(self, prefix: str = "") -> Iterable[StorageObjectInfo]:
        if not self.root.exists():
            return
        for path in self.root.rglob("*"):
            if not path.is_file() or not _STORAGE_KEY_RE.fullmatch(path.name):
                continue
            if prefix and not path.name.startswith(prefix):
                continue
            stat = path.stat()
            yield StorageObjectInfo(
                key=path.name,
                size_bytes=stat.st_size,
                last_modified=datetime.fromtimestamp(stat.st_mtime, tz=timezone.utc),
            )

    def health(self) -> bool:
        try:
            self.root.mkdir(parents=True, exist_ok=True)
            return os.access(self.root, os.W_OK)
        except OSError:
            return False

    def close(self) -> None:
        return None


class MinioStorage:
    """Private S3-compatible object storage backed by MinIO.

    The client used for uploads/downloads points at ``MINIO_ENDPOINT`` (the
    Compose service name inside Docker). A second client, configured with
    ``MINIO_PUBLIC_ENDPOINT``, is used only to sign client-facing URLs; it never
    connects to MinIO, so it can advertise the host-published address while the
    API continues to use the internal service name.
    """

    backend_name = "minio"

    def __init__(self, settings: Settings) -> None:
        self.bucket = settings.minio_bucket
        self._prefix = settings.minio_key_prefix
        self._max_read_bytes = settings.media_max_upload_bytes
        self._auto_create_bucket = settings.minio_auto_create_bucket
        self._settings = settings
        self._client = self._build_client(settings.minio_endpoint)
        self._public_client = self._client
        if settings.minio_public_endpoint != settings.minio_endpoint:
            self._public_client = self._build_client(settings.minio_public_endpoint)

    def _build_client(self, endpoint: str) -> Minio:
        settings = self._settings
        http_client = urllib3.PoolManager(
            timeout=urllib3.Timeout(
                connect=settings.minio_connect_timeout_seconds,
                read=settings.minio_read_timeout_seconds,
            ),
            retries=urllib3.Retry(
                total=settings.minio_max_retries,
                backoff_factor=0.2,
                status_forcelist=(500, 502, 503, 504),
                allowed_methods=frozenset({"GET", "HEAD", "PUT", "DELETE"}),
            ),
            maxsize=10,
            block=False,
        )
        return Minio(
            endpoint,
            access_key=settings.minio_access_key,
            secret_key=settings.minio_secret_key.get_secret_value(),
            secure=settings.minio_secure,
            region=settings.minio_region,
            http_client=http_client,
        )

    def _object_name(self, key: str) -> str:
        return f"{self._prefix}{_validate_key(key)}"

    @staticmethod
    def _is_not_found(exc: Exception) -> bool:
        return isinstance(exc, S3Error) and exc.code in {
            "NoSuchKey",
            "NoSuchObject",
            "NotFound",
        }

    def save(
        self,
        key: str,
        data: bytes,
        *,
        content_type: str | None = None,
    ) -> StoredObject:
        object_name = self._object_name(key)
        try:
            result = self._client.put_object(
                self.bucket,
                object_name,
                io.BytesIO(data),
                len(data),
                content_type=content_type or "application/octet-stream",
            )
        except (S3Error, MinioException, urllib3.exceptions.HTTPError) as exc:
            raise StorageError("could not store the object") from exc
        return StoredObject(
            backend=self.backend_name,
            etag=getattr(result, "etag", None),
        )

    def read(self, key: str) -> bytes:
        object_name = self._object_name(key)
        response = None
        try:
            response = self._client.get_object(self.bucket, object_name)
            data = response.read(self._max_read_bytes + 1)
            if len(data) > self._max_read_bytes:
                raise StorageError(
                    "stored object is larger than the configured limit"
                )
            return data
        except StorageError:
            raise
        except (S3Error, MinioException, urllib3.exceptions.HTTPError) as exc:
            if self._is_not_found(exc):
                raise StorageObjectNotFound("stored object is missing") from exc
            raise StorageError("could not read the object") from exc
        finally:
            if response is not None:
                response.close()
                response.release_conn()

    def delete(self, key: str) -> bool:
        object_name = self._object_name(key)
        try:
            self._client.stat_object(self.bucket, object_name)
        except (S3Error, MinioException, urllib3.exceptions.HTTPError) as exc:
            if self._is_not_found(exc):
                return False
            raise StorageError("could not inspect the object") from exc
        try:
            self._client.remove_object(self.bucket, object_name)
        except (S3Error, MinioException, urllib3.exceptions.HTTPError) as exc:
            raise StorageError("could not delete the object") from exc
        return True

    def exists(self, key: str) -> bool:
        object_name = self._object_name(key)
        try:
            self._client.stat_object(self.bucket, object_name)
            return True
        except (S3Error, MinioException, urllib3.exceptions.HTTPError) as exc:
            if self._is_not_found(exc):
                return False
            raise StorageError("could not inspect the object") from exc

    def presigned_url(self, key: str, *, expires_seconds: int) -> str:
        if expires_seconds <= 0:
            raise StorageError("presigned URL lifetime must be positive")
        try:
            return self._public_client.presigned_get_object(
                self.bucket,
                self._object_name(key),
                expires=timedelta(seconds=expires_seconds),
                response_headers={"response-content-disposition": "attachment"},
            )
        except (S3Error, MinioException, urllib3.exceptions.HTTPError) as exc:
            raise StorageError("could not create a download URL") from exc

    def iter_objects(self, prefix: str = "") -> Iterable[StorageObjectInfo]:
        list_prefix = f"{self._prefix}{prefix}"
        try:
            for item in self._client.list_objects(
                self.bucket, prefix=list_prefix, recursive=True
            ):
                name = item.object_name
                if self._prefix:
                    if not name.startswith(self._prefix):
                        continue
                    name = name[len(self._prefix) :]
                if not name:
                    continue
                last_modified = item.last_modified
                if last_modified.tzinfo is None:
                    last_modified = last_modified.replace(tzinfo=timezone.utc)
                yield StorageObjectInfo(
                    key=name,
                    size_bytes=int(item.size),
                    last_modified=last_modified,
                    etag=getattr(item, "etag", None),
                )
        except (S3Error, MinioException, urllib3.exceptions.HTTPError) as exc:
            raise StorageError("could not list stored objects") from exc

    def health(self) -> bool:
        try:
            return bool(self._client.bucket_exists(self.bucket))
        except (S3Error, MinioException, urllib3.exceptions.HTTPError):
            return False

    def ensure_bucket(self) -> None:
        """Create the bucket when explicitly enabled, otherwise fail clearly."""
        if self.health():
            return
        if not self._auto_create_bucket:
            raise StorageError(
                "the configured MinIO bucket is missing; run the bucket "
                "initialization service or enable MINIO_AUTO_CREATE_BUCKET"
            )
        try:
            self._client.make_bucket(self.bucket)
        except (S3Error, MinioException, urllib3.exceptions.HTTPError) as exc:
            raise StorageError("could not create the MinIO bucket") from exc

    def close(self) -> None:
        clients = [self._client]
        if self._public_client is not self._client:
            clients.append(self._public_client)
        for client in clients:
            pool = getattr(client, "_http", None)
            clear = getattr(pool, "clear", None)
            if callable(clear):
                clear()


def build_storage(settings: Settings) -> StorageService:
    """Build the configured backend.

    ``local`` is used by development/tests and ``minio`` by the Compose stack.
    Settings validates the allowed set and the MinIO credentials, so the final
    branch is defensive only.
    """
    if settings.media_storage_backend == "local":
        return LocalStorage(settings.media_storage_path)
    if settings.media_storage_backend == "minio":
        return MinioStorage(settings)
    raise ValueError(f"unsupported media storage backend: {settings.media_storage_backend}")
